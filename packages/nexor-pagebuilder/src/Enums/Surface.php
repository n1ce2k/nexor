<?php

namespace Nexor\PageBuilder\Enums;

/**
 * Где собирается раскладка из блоков.
 *
 * Сейчас работает только детальная страница элемента. `Page` — задел под
 * конструктор целых страниц сайта (главная, лендинги — как в шаблонах Аспро):
 * те же блоки плюс секции, привязанные к инфоблокам. Блок сам говорит, на
 * каких поверхностях он доступен (`Block::surfaces()`).
 */
enum Surface: string
{
    /** Детальная страница элемента инфоблока, вместо подробного текста. */
    case Detail = 'detail';

    /** Страница сайта целиком. Пока не используется — см. README модуля. */
    case Page = 'page';

    public function label(): string
    {
        return match ($this) {
            self::Detail => 'Детальная страница',
            self::Page => 'Страница сайта',
        };
    }
}
